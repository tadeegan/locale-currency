/**
 * Get the number of decimal places (minor unit exponent) for a currency.
 * Falls back to 2 for unknown currency codes.
 * @param {string} currency - ISO 4217 currency code (case insensitive)
 * @returns {number} Number of decimal places (0, 1, 2, or 3)
 */
export const getExponentForCurrency = (currency) => {
  return currencyDecimalMap[currency.toLowerCase()] ?? 2;
};

/**
 * Convert an amount in major units (e.g. dollars) to the currency's smallest
 * unit (e.g. cents), as an integer. Useful for payment APIs such as Stripe.
 * @param {number} amount - Amount in major units
 * @param {string} currency - ISO 4217 currency code (case insensitive)
 * @returns {number} Integer amount in the smallest currency unit
 */
export const convertToSmallestCurrencyUnit = (amount, currency) => {
  const exponent = getExponentForCurrency(currency);
  return Math.round(amount * Math.pow(10, exponent));
};
